from typing import Annotated, TypeAlias

Int16: TypeAlias = Annotated[int, 16]
Int32: TypeAlias = Annotated[int, 32]
Int64: TypeAlias = Annotated[int, 64]

Str16: TypeAlias = Annotated[str, 16]
Str32: TypeAlias = Annotated[str, 32]
Str64: TypeAlias = Annotated[str, 64]
Str128: TypeAlias = Annotated[str, 64]
Str256: TypeAlias = Annotated[str, 64]
